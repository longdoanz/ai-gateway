# -*- coding: utf-8 -*-

"""
Entity patterns for the PII guardrail, plus the cheap gates that keep the
scan off the hot path.

Two classes of entity:

- ``PII_PATTERNS``   — tokenized on the way up, restored on the way back.
- ``SECRET_PATTERNS``— never forwarded. A match is a hard, deterministic
  reject; there is nothing to restore because the value never leaves.

Why the gates exist
-------------------
Measured on a 588KB payload (the size ``payload_guards`` trims to), running
all patterns over every text field costs ~126ms — no single pattern is hot,
the cost is simply ``patterns x bytes`` because ``re`` walks every position.
Gating each pattern behind a literal substring test (``str.__contains__`` is
memchr-backed C) and funnelling all numeric patterns through one shared
digit-run gate brings the same scan to ~8.5ms with identical results.

The gate must be strictly *weaker* than every pattern it guards, and numeric
spans are padded before the real patterns run — with no padding the gate
silently drops matches whose pattern needs a prefix outside the digit run
(e.g. the ``+`` of ``+84 90 123 4567``): measured 84 hits instead of 105.

Secret rules are vendored from gitleaks (see ``kiro/guardrails/secret_rules.py``,
generated by ``scripts/gen_secret_rules.py``) rather than hand-rolled: a
community-maintained ruleset of 200+ formats beats us reinventing a handful.
The same "gate before you run the expensive pattern" idea applies, just with
many keywords instead of one — see ``_SECRET_KEYWORD_GATE`` below.
"""

import re

from kiro.guardrails.secret_rules import GITLEAKS_SECRET_RULES, GITLEAKS_VERSION, SecretRule

# Exposed so /health or a test can report which ruleset is live without
# reaching into the generated module directly.
SECRET_RULESET_VERSION = GITLEAKS_VERSION

# Padding applied around a digit-run gate match before the numeric patterns
# run against the span. Must cover the longest non-digit prefix any numeric
# pattern can require ("+84 " is 4). Verified lossless at >= 4.
NUMERIC_GATE_PAD = 6

# Finds runs that could hold a 9+ digit identifier. Deliberately permissive:
# separators are allowed inside so "4111 1111 1111 1111" stays one span.
DIGIT_GATE = re.compile(r"\d[\d .\-]{7,}\d")


# --- PII: tokenized and restored -------------------------------------------

# (entity_type, compiled pattern). Gated by DIGIT_GATE.
NUMERIC_PII: list[tuple[str, re.Pattern]] = [
    ("PHONE_VN", re.compile(r"(?:\+84[ .-]?|\b0)(?:\d[ .-]?){8,9}\d\b")),
    ("CCCD", re.compile(r"\b\d{12}\b")),
    ("CARD", re.compile(r"\b(?:\d[ -]?){12,18}\d\b")),
    ("IPV4", re.compile(r"\b(?:\d{1,3}\.){3}\d{1,3}\b")),
    ("IBAN", re.compile(r"\b[A-Z]{2}\d{2}[A-Z0-9]{11,30}\b")),
]

# (entity_type, required literal, compiled pattern).
LITERAL_PII: list[tuple[str, str, re.Pattern]] = [
    ("EMAIL", "@", re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.-]{2,}\b")),
]


# --- Secrets: blocked, never forwarded -------------------------------------
