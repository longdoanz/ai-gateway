# --- Secret validators ------------------------------------------------------
#
# Measured against this repo, the raw patterns fire on things a coding agent
# legitimately reads: PEM headers mentioned (not embedded) in library source,
# short placeholder keys in integration docs, JWT-shaped strings built up
# from variables inside source code. Blocking on those would break the agent
# constantly, so each pattern gets a second stage that looks for evidence the
# match is a real, live credential rather than a mention of one. These run
# in addition to — never instead of — gitleaks' own entropy/allowlist gates
# on the vendored rules (see secret_rules.py's SecretRule.min_entropy/allow).
#
# Signature: (secret_value, full_text, start, end) -> bool, where
# secret_value is the rule's secret_group capture (whole match if 0), i.e.
# the credential itself with the trailing boundary/quote junk stripped.

_B64_RUN = re.compile(r"[A-Za-z0-9+/=]{40,}")

# Published example credentials that appear in vendor documentation.
_KNOWN_EXAMPLES = frozenset({
    "AKIAIOSFODNN7EXAMPLE",
    "ASIAIOSFODNN7EXAMPLE",
})


def _real_private_key(matched: str, _text: str, _start: int, _end: int) -> bool:
    """A PEM header is only a key if the captured block has real key
    material in it, not just a header/footer with prose in between.

    The vendored gitleaks pattern already requires >=64 chars between an
    opening and a matching closing marker, and captures the whole block
    (header + body + footer) as the match — so unlike the old hand-written
    pattern, there is no "text after the match" to look ahead into; the
    body is inside ``matched`` itself.
    """
    return bool(_B64_RUN.search(matched))


def _real_openai_key(matched: str, _text: str, _start: int, _end: int) -> bool:
    """Real OpenAI keys are long; doc placeholders are short stubs."""
    body = matched.split("-", 2)[-1]
    return len(body) >= 40


def _real_jwt(matched: str, _text: str, _start: int, _end: int) -> bool:
    """A JWT's first segment must decode to a JSON header declaring an alg."""
    import base64
    import json as _json

    head = matched.split(".", 1)[0]
    try:
        padded = head + "=" * (-len(head) % 4)
        claims = _json.loads(base64.urlsafe_b64decode(padded))
    except Exception:
        return False
    return isinstance(claims, dict) and "alg" in claims


def _not_a_known_example(matched: str, _text: str, _start: int, _end: int) -> bool:
    return matched not in _KNOWN_EXAMPLES


