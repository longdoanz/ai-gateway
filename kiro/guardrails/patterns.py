def _valid_iban(text: str) -> bool:
    """ISO 13616 / mod-97 checksum, so a 16-digit card or other digit run
    that happens to look like ``[A-Z]{2}\\d{2}...`` doesn't get flagged as an
    IBAN, and a genuinely mistyped IBAN doesn't get tokenized as if real."""
    candidate = "".join(text.split()).upper()
    if len(candidate) < 4 or not candidate[:2].isalpha() or not candidate[2:4].isdigit():
        return False
    expected_len = _IBAN_LENGTH_BY_COUNTRY.get(candidate[:2])
    if expected_len is not None and len(candidate) != expected_len:
        return False
    # Move the 4-char country+checksum prefix to the end, then map letters to
    # numbers (A=10..Z=35) before reducing mod 97 — the ISO 13616 algorithm.
    rearranged = candidate[4:] + candidate[:4]
    if not rearranged.isalnum():
        return False
    numeric = "".join(str(int(c, 36)) for c in rearranged)
    return int(numeric) % 97 == 1


